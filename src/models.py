"""
Pydantic data models for structured inputs and outputs in Agentic Travel Planner.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class FlightOption(BaseModel):
    """Details of a selected flight."""
    flight_id: str = Field(description="Unique identifier for the flight")
    airline: str = Field(description="Airline operating the flight")
    origin: str = Field(description="Origin city")
    destination: str = Field(description="Destination city")
    departure_time: str = Field(description="Departure timestamp ISO string")
    arrival_time: str = Field(description="Arrival timestamp ISO string")
    duration: Optional[str] = Field(default=None, description="Formatted duration e.g. '2h 15m'")
    price: float = Field(description="Price in INR")
    selection_reason: Optional[str] = Field(default=None, description="Why this flight was selected")


class HotelOption(BaseModel):
    """Details of a recommended hotel."""
    hotel_id: str = Field(description="Unique identifier for the hotel")
    name: str = Field(description="Hotel name")
    city: str = Field(description="City location")
    stars: int = Field(description="Star rating (1 to 5)")
    price_per_night: float = Field(description="Price per night in INR")
    amenities: List[str] = Field(default_factory=list, description="Available amenities")
    selection_reason: Optional[str] = Field(default=None, description="Why this hotel was chosen")


class PlaceOption(BaseModel):
    """Details of a recommended tourist attraction."""
    place_id: str = Field(description="Unique identifier for the place")
    name: str = Field(description="Name of the place")
    city: str = Field(description="City")
    type: str = Field(description="Category e.g. fort, temple, beach, museum, lake, park, market")
    rating: float = Field(description="Visitor rating out of 5.0")
    recommended_time: Optional[str] = Field(default=None, description="Morning / Afternoon / Evening")
    description: Optional[str] = Field(default=None, description="Brief description or tip")


class DayWeather(BaseModel):
    """Weather expectation for a specific day."""
    day: int = Field(description="Day number of the trip (1, 2, ...)")
    date: Optional[str] = Field(default=None, description="Calendar date YYYY-MM-DD")
    condition: str = Field(description="Condition e.g. Sunny, Partly Cloudy, Light Rain")
    icon: Optional[str] = Field(default="☀️", description="Emoji icon")
    temp_max: float = Field(description="Max temperature in Celsius")
    temp_min: float = Field(description="Min temperature in Celsius")
    tip: Optional[str] = Field(default=None, description="Travel weather advisory")


class DayPlan(BaseModel):
    """Itinerary for a single day."""
    day: int = Field(description="Day number")
    date: Optional[str] = Field(default=None, description="Calendar date")
    theme: Optional[str] = Field(default=None, description="Theme of the day e.g. Heritage & Culture")
    weather: Optional[DayWeather] = Field(default=None, description="Weather forecast for the day")
    morning_activity: str = Field(description="Morning attraction or activity")
    afternoon_activity: str = Field(description="Afternoon attraction or activity")
    evening_activity: str = Field(description="Evening attraction or activity")
    places: List[PlaceOption] = Field(default_factory=list, description="List of attractions visited")
    meals_and_tips: Optional[str] = Field(default=None, description="Local dining tip or transport note")


class BudgetBreakdown(BaseModel):
    """Itemized budget estimate."""
    flight_cost: float = Field(description="Total flight cost for all travelers")
    hotel_cost: float = Field(description="Total hotel accommodation cost")
    food_and_travel: float = Field(description="Total local food, transit, and entry tickets")
    buffer_cost: float = Field(default=0.0, description="Contingency buffer")
    total_cost: float = Field(description="Total estimated budget in INR")
    per_person_cost: float = Field(description="Cost per person in INR")
    currency: str = Field(default="INR", description="Currency symbol/code")


class TripItinerary(BaseModel):
    """Complete trip itinerary generated by the agent."""
    trip_title: str = Field(description="Title e.g. 'Your 3-Day Trip to Goa (Feb 12–14)'")
    origin: str = Field(description="Origin city")
    destination: str = Field(description="Destination city")
    start_date: str = Field(description="Start date YYYY-MM-DD")
    end_date: str = Field(description="End date YYYY-MM-DD")
    days: int = Field(description="Trip duration in days")
    travelers: int = Field(default=1, description="Number of travelers")
    flight_selected: FlightOption = Field(description="Selected flight details")
    hotel_booked: HotelOption = Field(description="Recommended hotel details")
    weather_forecast: List[DayWeather] = Field(default_factory=list, description="Day-wise weather")
    itinerary: List[DayPlan] = Field(default_factory=list, description="Day-by-day plan")
    estimated_total_budget: BudgetBreakdown = Field(description="Itemized budget")
    decision_reasoning: Optional[str] = Field(default=None, description="Why these options were selected")
    raw_query: Optional[str] = Field(default=None, description="Original user prompt or requirements")


class TravelQuery(BaseModel):
    """User input travel request."""
    origin: str = Field(description="Source city e.g. Delhi")
    destination: str = Field(description="Destination city e.g. Goa")
    start_date: Optional[str] = Field(default=None, description="Trip start date YYYY-MM-DD")
    days: int = Field(default=3, ge=1, le=14, description="Duration in days")
    travelers: int = Field(default=1, ge=1, le=10, description="Number of travelers")
    budget_tier: str = Field(default="moderate", description="budget / moderate / luxury")
    preferred_types: Optional[List[str]] = Field(default=None, description="Preferred attraction categories")
    flight_preference: str = Field(default="cheapest", description="cheapest / fastest / earliest")
    min_hotel_stars: int = Field(default=3, ge=1, le=5, description="Minimum hotel star rating")
